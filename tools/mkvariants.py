#!/usr/bin/env python3
"""Write <ward dir>/variants.js — "โจทย์แนวใหม่ที่อาจออก" (variants) for old-exam MCQ / MEQ / OSCE items that lack them.

User rule (27 Oct 2026): every OLD-EXAM item (MCQ, MEQ, OSCE — every site: MDCU, SI, โพยหมอ NL/Compre) always has
"โจทย์แนวใหม่ที่อาจออก"; AI-written questions (Unit / Admission / Specialty / Legendary AI) never do.
New old-exam data should carry `variants` directly in data_b*/meq_b*/osce_b*; this overlay fills older items.

usage: python3 tools/mkvariants.py <ward dir> MCQ=<map.json> MEQ=<map.json> OSCE=<map.json>   (any subset)
map.json = {"<set>|<ro>|<orig>[@p<page>][~n]": ["…", "…", "…"], …}  — key scheme identical to meq_fixes.js
An item that already has variants is left alone. build_site.py loads variants.js after the MCQ/MEQ/OSCE banks.
"""
import json, os, sys

d = sys.argv[1]
VAR = {}
for a in sys.argv[2:]:
    t, f = a.split('=', 1)
    assert t in ('MCQ', 'MEQ', 'OSCE'), t
    m = json.load(open(f, encoding='utf-8'))
    for k, v in m.items():
        assert isinstance(v, list) and v and all(isinstance(x, str) and x.strip() for x in v), k
    VAR.setdefault(t, {}).update(m)

js = ('/* AUTO-GENERATED by tools/mkvariants.py — "โจทย์แนวใหม่ที่อาจออก" for old-exam items (user rule 27 Oct 2026). Keys set|ro|orig (+@p<page>/~n). */\n'
      '(function(){const VAR=' + json.dumps(VAR, ensure_ascii=False, separators=(',', ':')) + ';\n'
      'const ap=(L,T)=>{const M=VAR[T];if(!M||!L)return;const c={};L.forEach(q=>{const b=q.set+"|"+(q.ro||"")+"|"+q.orig;c[b]=(c[b]||0)+1;});\n'
      '  const seen={},hit={};L.forEach(q=>{let b=q.set+"|"+(q.ro||"")+"|"+q.orig;if(c[b]>1)b+="@p"+q.page;if(seen[b])b+="~"+(++seen[b]);else seen[b]=1;\n'
      '    if(M[b]){hit[b]=1;if(!(q.variants||[]).length)q.variants=M[b];}});\n'
      '  if(typeof console!=="undefined")Object.keys(M).forEach(k=>{if(!hit[k])console.warn("variants.js: no "+T+" item for",k);});};\n'
      'ap(W.QB,"MCQ");ap(W.MQ,"MEQ");ap(W.OS,"OSCE");})();\n')
out = os.path.join(d, 'variants.js')
open(out, 'w', encoding='utf-8').write(js)
print(out, {t: len(m) for t, m in VAR.items()}, len(js.encode()), 'bytes')
