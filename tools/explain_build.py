#!/usr/bin/env python3
"""รวมแพตช์เฉลยข้อสอบเก่า (AC MCQ) → <dir>/explain.js  (ผู้ใช้สั่ง 23 พ.ย. 2026: เฉลยต้องครบ 100% ทุกข้อ ทวทว)

แพตช์: parts/explain/<slug>/pNN.json  (slug = ชื่อโฟลเดอร์วอร์ด เช่น data_subspe, si_data_med)
  {"MDCU66|RoA|X19": {"interp": "...", "why": "...", "wrong": {"A": "...", ...}, "trap": "...", "summary": ["...", ...]}}
  ถ้า set|ro|orig ซ้ำกันในวอร์ด ใช้ "set|ro|orig@p<page>" · ถ้าซ้ำในหน้าเดียวกันด้วย ใช้ "set|ro|orig@p<page>#<n>" (n = ลำดับที่ในหน้านั้น ตามที่ ac_dump แสดง)
  ฟิลด์ที่ใส่ = แทนทั้งฟิลด์ · ไฟล์หลังทับไฟล์ก่อน (เรียงชื่อไฟล์)
explain.js โหลดหลัง fixes.js และ opinions.js (build_site.py, tools/load.js)

python3 tools/explain_build.py            # ทุกวอร์ดที่มีแพตช์
python3 tools/explain_build.py data_ped   # วอร์ดเดียว
"""
import glob, json, os, re, sys
LT = re.compile(r"<(?!/?(?:b|i|u|br|sup|sub|small)\b)")   # "<" ในข้อความ (เช่น pH < 7.2) → &lt; ไม่ให้หน้าเว็บกลืนเป็นแท็ก
esc = lambda v: LT.sub("&lt;", v) if isinstance(v, str) else [esc(x) for x in v] if isinstance(v, list) else {k: esc(x) for k, x in v.items()} if isinstance(v, dict) else v
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OK = {"interp", "why", "wrong", "trap", "summary", "mnemonic", "opinion", "variants", "guide", "notes", "kimg", "src"}  # guide/notes/kimg/src เพิ่ม 26 พ.ย. 2026: เฉลยข้อสอบเก่ารูปแบบ PDF L28 (ทริคจำ · อ้างอิง · ถอดตัวพิมพ์+ลายมือจากไฟล์)

def build(slug):
    d = slug.replace("si_", "si/", 1) if slug.startswith("si_") else slug
    ex = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "parts/explain", slug, "*.json"))):
        for k, v in json.load(open(f, encoding="utf-8")).items():
            bad = set(v) - OK
            if bad: sys.exit(f"{f}: {k}: ฟิลด์ไม่รู้จัก {bad}")
            ex.setdefault(k, {}).update(esc(v))
    js = ("/* AUTO-GENERATED by tools/explain_build.py จาก parts/explain/%s/*.json — อย่าแก้มือ\n"
          "   เฉลยข้อสอบเก่าเขียนใหม่ให้ครบทุกพาร์ท (ตีความโจทย์ · ทำไมถูก · ทำไมข้ออื่นผิด · กับดัก · สรุป) — 23 พ.ย. 2026 */\n"
          "(function(){const EX=%s;\nconst hit={},oc={};QB.forEach(q=>{const b=q.set+\"|\"+(q.ro||\"\")+\"|\"+q.orig,bp=b+\"@p\"+q.page,n=oc[bp]=(oc[bp]||0)+1;const k=EX[bp+\"#\"+n]?bp+\"#\"+n:EX[bp]?bp:b;const f=EX[k];if(f){Object.assign(q,f);hit[k]=1;}});\n"
          "if(typeof console!==\"undefined\")Object.keys(EX).forEach(k=>{if(!hit[k])console.warn(\"explain.js: no question for\",k);});})();\n"
          ) % (slug, json.dumps(ex, ensure_ascii=False, separators=(",", ":")))
    open(os.path.join(ROOT, d, "explain.js"), "w", encoding="utf-8").write(js)
    print(f"{d}/explain.js: {len(ex)} ข้อ")
    # ตัวกันคุณภาพ (24 พ.ย. 2026): แพตช์ zq* ต้องผ่าน tools/explain_quality.js ทุกข้อ ไม่งั้นหยุด
    import subprocess
    r = subprocess.run(["node", os.path.join(ROOT, "tools/explain_gate.js"), slug], env={**os.environ, "DIR": d}, capture_output=True, text=True)
    print(r.stdout.rstrip() or r.stderr.rstrip())
    if r.returncode: sys.exit(f"❌ {slug}: gate ไม่ผ่าน — ห้าม build/push จนกว่าจะแก้แพตช์ zq*")

slugs = sys.argv[1:] or sorted(os.path.basename(p) for p in glob.glob(os.path.join(ROOT, "parts/explain/*")) if os.path.isdir(p))
for s in slugs: build(s)
